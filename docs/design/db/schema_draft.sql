-- 스마트박물관 AI Agent RDB 스키마 초안 (Agent 제안, Web 확정)
-- DB: Oracle Database (Oracle Database Free 23ai에서 실행 확인, 12c 이상 문법만 사용)
-- 근거: 인터페이스 명세 4.4 기록 저장 API, 8장 유물 기본 정보, 요구사항 FR-WEB-01·02·08·09·10·11·14
--
-- Oracle 주의
--   - 문자열은 VARCHAR2(n CHAR): 한글 한 글자가 UTF-8로 3바이트라 CHAR를 빼면 n바이트까지만 들어감
--   - 빈 문자열 ''은 NULL로 저장됨: NOT NULL 열에 ''을 넣으면 오류(ORA-01400). Flask에서 빈 값은 None으로 보냄
--   - 참/거짓은 NUMBER(1) 0/1 (23ai 이전 버전과 호환)
--   - JSON 배열은 CLOB + IS JSON 검사
--   - 시각은 TIMESTAMP(3)에 오프셋 없는 한국 시각(설계 문서 4장)
--   - size는 예약어라 열 이름을 size_info로 둠(유물 초기 데이터 JSON의 size → size_info)

-- FR-WEB-01 관리자 로그인(단일 계정)
CREATE TABLE admin_users (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(50 CHAR)  NOT NULL UNIQUE,
    password_hash VARCHAR2(255 CHAR) NOT NULL,          -- werkzeug.security.generate_password_hash
    created_at    TIMESTAMP(3) DEFAULT LOCALTIMESTAMP NOT NULL
);

-- FR-WEB-02 유물 정보. 초기 데이터 docs/interface/samples/artifacts_seed.json
CREATE TABLE artifacts (
    artifact_id   VARCHAR2(10 CHAR)  PRIMARY KEY,       -- A001 (세 모듈 공통 키)
    collection_no VARCHAR2(30 CHAR)  NOT NULL UNIQUE,   -- 소장품 번호 본관9663
    emuseum_id    VARCHAR2(30 CHAR)  UNIQUE,
    name          VARCHAR2(100 CHAR) NOT NULL,          -- 화면 표시 이름
    name_official VARCHAR2(255 CHAR),                   -- e뮤지엄 공식 명칭
    era           VARCHAR2(30 CHAR),                    -- 시대 신라·조선·고려
    era_detail    VARCHAR2(50 CHAR),                    -- 1622년, 15~16세기경
    museum        VARCHAR2(100 CHAR) NOT NULL,          -- 소장처
    designation   VARCHAR2(30 CHAR),                    -- 국보·보물
    material      VARCHAR2(100 CHAR),
    size_info     VARCHAR2(100 CHAR),                   -- JSON의 size
    author        VARCHAR2(100 CHAR),
    description   CLOB,
    display_kind  VARCHAR2(10 CHAR)  NOT NULL CHECK (display_kind IN ('SHOWCASE','OPEN','WALL')),
    role          VARCHAR2(10 CHAR)  NOT NULL CHECK (role IN ('DEMO','SPARE')),
    created_at    TIMESTAMP(3) DEFAULT LOCALTIMESTAMP NOT NULL,
    updated_at    TIMESTAMP(3) DEFAULT LOCALTIMESTAMP NOT NULL
);

-- A002 복장물처럼 따로 등록하지 않는 부속 소장품(조회 화면 참고 정보)
CREATE TABLE artifact_related_items (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artifact_id   VARCHAR2(10 CHAR)  NOT NULL REFERENCES artifacts(artifact_id) ON DELETE CASCADE,
    collection_no VARCHAR2(30 CHAR)  NOT NULL UNIQUE,
    emuseum_id    VARCHAR2(30 CHAR),
    name          VARCHAR2(255 CHAR) NOT NULL,
    designation   VARCHAR2(30 CHAR)
);
CREATE INDEX ix_related_artifact ON artifact_related_items (artifact_id);

-- FR-WEB-08 침범 기록. POST로 열고 PATCH로 갱신·닫음(명세 4.4)
CREATE TABLE intrusion_records (
    record_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id         VARCHAR2(40 CHAR) NOT NULL UNIQUE,  -- 연 이벤트(evt-… 또는 sync-…). 같은 값이 다시 오면 기존 record_id 반환
    zone_id          VARCHAR2(10 CHAR) NOT NULL,
    artifact_id      VARCHAR2(10 CHAR) NOT NULL REFERENCES artifacts(artifact_id),  -- 침범 당시 유물(교체돼도 기록은 유지)
    start_level      VARCHAR2(10 CHAR) NOT NULL CHECK (start_level IN ('CAUTION','WARNING')),
    max_level        VARCHAR2(10 CHAR) NOT NULL CHECK (max_level IN ('CAUTION','WARNING')),
    cause            VARCHAR2(20 CHAR) CHECK (cause IN ('LINE_1','LINE_2','TOUCH','CAUTION_TIMEOUT')),  -- 마지막으로 단계를 올린 원인, 동기화 기록은 NULL
    visitor_ids      CLOB DEFAULT '[]' NOT NULL CHECK (visitor_ids IS JSON),  -- 정수 배열, 닫을 때 침범자 전원으로 바뀜
    started_at       TIMESTAMP(3) NOT NULL,              -- CV 이벤트 timestamp
    ended_at         TIMESTAMP(3),                       -- NULL = "종료 미확인"
    duration_ms      NUMBER(10),                         -- 닫을 때 Flask가 계산
    session_id       VARCHAR2(40 CHAR),                  -- 당시 세션(세션 기록은 끝날 때 생기므로 FK 아님)
    session_paused   NUMBER(1) DEFAULT 0 NOT NULL CHECK (session_paused IN (0,1)),
    repeated_caution NUMBER(1) DEFAULT 0 NOT NULL CHECK (repeated_caution IN (0,1)),
    last_event_id    VARCHAR2(40 CHAR),                  -- 마지막 PATCH의 event_id(재시도 중복 확인용)
    created_at       TIMESTAMP(3) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX ix_intrusion_artifact_started ON intrusion_records (artifact_id, started_at);
CREATE INDEX ix_intrusion_started ON intrusion_records (started_at);

-- FR-WEB-09 세션 기록. 세션이 끝날 때 한 번 POST(명세 4.4)
CREATE TABLE docent_sessions (
    session_id        VARCHAR2(40 CHAR) PRIMARY KEY,     -- ses-Z01-20261120-140300000
    zone_id           VARCHAR2(10 CHAR) NOT NULL,
    artifact_id       VARCHAR2(10 CHAR) NOT NULL REFERENCES artifacts(artifact_id),
    started_at        TIMESTAMP(3) NOT NULL,
    ended_at          TIMESTAMP(3) NOT NULL,
    end_reason        VARCHAR2(30 CHAR) NOT NULL CHECK (end_reason IN
                        ('LEFT_AFTER_COMPLETE','LEFT_DURING_NARRATION','LEFT_WHILE_PAUSED',
                         'LEFT_WHILE_SPEAKER_WAIT','NEW_SESSION')),
    start_count       NUMBER(5) NOT NULL,                -- 시작 인원
    script_end_count  NUMBER(5) DEFAULT 0 NOT NULL,      -- 원고 끝 시점 인원
    completed_count   NUMBER(5) DEFAULT 0 NOT NULL,      -- 끝까지 들은 인원
    script            CLOB,                              -- 생성 원고(대체 해설이면 그 원고)
    rag_chunk_ids     CLOB DEFAULT '[]' NOT NULL CHECK (rag_chunk_ids IS JSON),  -- 문자열 배열
    source_urls       CLOB DEFAULT '[]' NOT NULL CHECK (source_urls IS JSON),    -- 문자열 배열
    fallback_used     NUMBER(1) DEFAULT 0 NOT NULL CHECK (fallback_used IN (0,1)),
    generation_failed NUMBER(1) DEFAULT 0 NOT NULL CHECK (generation_failed IN (0,1)),  -- 해설 도중 생성 실패(명세 7장 안건 10)
    created_at        TIMESTAMP(3) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX ix_session_artifact_started ON docent_sessions (artifact_id, started_at);

-- FR-WEB-14 규칙 위반 기록
CREATE TABLE violation_records (
    record_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id     VARCHAR2(40 CHAR) NOT NULL UNIQUE,
    zone_id      VARCHAR2(10 CHAR) NOT NULL,
    artifact_id  VARCHAR2(10 CHAR) NOT NULL REFERENCES artifacts(artifact_id),
    visitor_id   NUMBER(10) NOT NULL,
    item_type    VARCHAR2(20 CHAR) NOT NULL CHECK (item_type IN ('TAKEOUT_CUP')),
    occurred_at  TIMESTAMP(3) NOT NULL,
    created_at   TIMESTAMP(3) DEFAULT LOCALTIMESTAMP NOT NULL
);
CREATE INDEX ix_violation_artifact_occurred ON violation_records (artifact_id, occurred_at);
